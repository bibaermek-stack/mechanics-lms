// Scripts for the ten lesson films: how long each runs and what the caption says
// at every moment. The scenes in src/components/lesson3d/scenes time their
// animation against these chapters, and the render tool writes the same lines
// out as a .vtt file — so editing a caption or its timing happens here, once.
//
// Captions double as the narration. They are written to be read aloud, so a
// teacher can record a voice-over to the same timings and drop it in
// tools/videos/narration/ (see tools/videos/README.md).

import type { LessonScript } from "@/lib/studio/timeline";

/** Where a lesson's rendered film is served from (see tools/videos/README.md). */
export function lessonVideoSrc(moduleId: number): string {
  return `/videos/lesson-${String(moduleId).padStart(2, "0")}.mp4`;
}

/** Whole seconds a lesson's film runs; the render tool produces exactly this length. */
export function lessonVideoSeconds(moduleId: number): number {
  return Math.round(LESSON_SCRIPTS[moduleId]?.duration ?? 0);
}

/**
 * The poster frame and caption file the render tool writes next to a lesson's
 * film. They exist only for the bundled films: a teacher who points a lesson at
 * some other video gets a plain player, with that video's own first frame.
 */
export function videoSidecars(src: string): { poster?: string; captions?: string } {
  return /^\/videos\/lesson-\d+\.mp4$/.test(src)
    ? { poster: src.replace(/\.mp4$/, ".jpg"), captions: src.replace(/\.mp4$/, ".vtt") }
    : {};
}

/** "1 мин 29 сек" — lessons are short enough that bare minutes would round them to nothing. */
export function formatVideoLength(seconds: number): string {
  const s = Math.max(0, Math.round(seconds));
  const m = Math.floor(s / 60);
  const r = s % 60;
  if (m === 0) return `${r} сек`;
  return r === 0 ? `${m} мин` : `${m} мин ${r} сек`;
}

