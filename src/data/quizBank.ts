// Extra quiz questions, on top of the ones each lesson was written with.
//
// Lessons 3–10 shipped with five questions each and every one of them was a
// definition ("What is stress?"). That is a quiz a student can finish in a minute
// and learn nothing new from on the second try. The questions here fill the gap
// in two ways:
//
//   • Conceptual questions, written by hand — what happens to the weight in a
//     lift, why a soft landing hurts less, why a ship floats.
//   • Numerical questions whose answers are *computed*, not typed. Each one calls
//     the formula bank (src/data/formulas.ts, which has its own round-trip tests)
//     and builds the question text, the right answer, the explanation and the
//     wrong answers from the same numbers. A typo in "8 kg" can therefore not
//     disagree with a correct answer worked out for "6 kg".
//
// The wrong answers of a numerical question are the slips a student actually
// makes — forgetting the ½ in kinetic energy, dividing where one should multiply,
// leaving the unit prefix out — not random numbers, so a wrong choice says
// something about the misunderstanding.
//
// With the original questions each lesson now has a bank of fifteen. A quiz draws
// ten of them at random (see drawQuiz in modules.ts), so a retry is a different
// quiz instead of the same five questions in a new order.

import { FORMULAS } from "./formulas";

export interface QuizSeed {
  q: string;
  correct: string;
  wrong: [string, string, string];
  explanation: string;
  /** Set on questions built by numeric(): their numbers come from the formula bank. */
  kind?: "numeric";
}

// ---------------------------------------------------------------------------
// Number formatting — Kazakh writes the decimal mark as a comma
// ---------------------------------------------------------------------------

/** 3,14 · 0,002 · 18 000 — comma for decimals, a no-break space after thousands. */
export function fmt(n: number, maxDecimals = 2): string {
  const rounded = Number(n.toFixed(maxDecimals));
  let s = Math.abs(rounded).toFixed(maxDecimals);
  if (s.includes(".")) s = s.replace(/0+$/, "").replace(/\.$/, "");
  const [int, dec] = s.split(".");
  const grouped = int.length >= 5 ? int.replace(/\B(?=(\d{3})+(?!\d))/g, " ") : int;
  return `${rounded < 0 ? "−" : ""}${grouped}${dec ? `,${dec}` : ""}`;
}

/** Applies a formula from the bank. Throws if the id or the unknown does not exist. */
export function solve(formulaId: string, unknown: string, given: Record<string, number>): number {
  const f = FORMULAS.find((x) => x.id === formulaId);
  const fn = f?.solve[unknown];
  if (!fn) throw new Error(`quizBank: no solver for ${unknown} in "${formulaId}"`);
  return fn(given);
}

// ---------------------------------------------------------------------------
// The numerical question builder
// ---------------------------------------------------------------------------

interface NumericSpec {
  /** Question text. `{name}` is replaced by the formatted value of `shown.name`. */
  text: string;
  /** The numbers the student sees. */
  shown: Record<string, number>;
  /** The right answer, computed by the caller from the formula bank. */
  answer: number;
  unit: string;
  /** Wrong answers a student gets by a typical slip, most tempting first. */
  slips: number[];
  /** Why; `{ans}` and `{name}` are replaced as in `text`. */
  explanation: string;
  decimals?: number;
}

/**
 * Fills `{name}` placeholders. Numbers the student is *given* are printed exactly
 * (up to six decimals): rounding them to the precision of the answer once turned
 * "0,0006 м²" into "0 м²" and "0,0005" into "0,001" — a question whose text
 * disagreed with the number its answer had been computed from. Only the answer
 * is rounded to `decimals`.
 */
function fill(template: string, values: Record<string, number>, decimals: number): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => {
    if (!(key in values)) throw new Error(`quizBank: "{${key}}" has no value in "${template}"`);
    return fmt(values[key], key === "ans" ? decimals : 6);
  });
}

function numeric(spec: NumericSpec): QuizSeed {
  const d = spec.decimals ?? 2;
  const show = (v: number) => `${fmt(v, d)}${spec.unit ? ` ${spec.unit}` : ""}`;
  const correct = show(spec.answer);

  // Wrong answers: the slips first, then plain scalings, never a repeat of the
  // right answer or of each other once they are printed.
  const seen = new Set([correct]);
  const wrong: string[] = [];
  const fallbacks = [spec.answer * 2, spec.answer / 2, spec.answer * 10, spec.answer / 10, spec.answer + 1, spec.answer * 1.5];
  for (const v of [...spec.slips, ...fallbacks]) {
    if (!Number.isFinite(v) || wrong.length === 3) continue;
    const text = show(v);
    if (seen.has(text)) continue;
    seen.add(text);
    wrong.push(text);
  }

  const values = { ...spec.shown, ans: spec.answer };
  return {
    q: fill(spec.text, values, d),
    correct,
    wrong: wrong as [string, string, string],
    explanation: fill(spec.explanation, values, d),
    kind: "numeric",
  };
}

